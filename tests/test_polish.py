"""v0.19 polish found by running the try-it guide. Written by the architect; implementation must pass it unchanged.
- Singular wording for one job: "1 job analysed", "Top 1 job by wasted core-hours".
- `--version` prints "clusterflow 0.19" (clusterflow_cli.VERSION = "0.19"); the HTML footer names the version, so a
  report sent around says which build made it."""
import os
import subprocess
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..")
CLI = os.path.join(ROOT, "backend", "clusterflow_cli.py")
BUNDLE = os.path.join(ROOT, "dist", "clusterflow.py")
sys.path.insert(0, os.path.join(ROOT, "backend"))
import analysis  # noqa: E402
import clusterflow_cli  # noqa: E402

ONE = ("JobID|State|Elapsed|Timelimit|AllocCPUS|TotalCPU|ReqMem|MaxRSS\n"
       "1|COMPLETED|01:00:00|02:00:00|2|01:00:00|2G|\n1.batch|COMPLETED|01:00:00||2|01:00:00||1G\n")


def run(*args, script=CLI):
    env = dict(os.environ, PYTHONIOENCODING="utf-8")
    return subprocess.run([sys.executable, script, *args], stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                          universal_newlines=True, encoding="utf-8", env=env, timeout=60)


def test_singular_wording():
    text = clusterflow_cli.report(analysis.analyze(ONE), 5)
    assert text.startswith("ClusterFlow report: 1 job analysed")
    assert "Top 1 job by wasted core-hours" in text


def test_plural_unchanged():
    text = clusterflow_cli.report(analysis.analyze(clusterflow_cli.DEMO_SACCT), 5)
    assert text.startswith("ClusterFlow report: 32 jobs analysed")
    assert "Top 5 jobs by wasted core-hours" in text


def test_version_flag():
    for script in (CLI, BUNDLE):
        p = run("--version", script=script)
        assert p.returncode == 0
        assert p.stdout.strip() == "clusterflow " + clusterflow_cli.VERSION


def test_html_footer_names_version():
    page = clusterflow_cli.html_report(analysis.analyze(ONE), 5)
    assert "Generated by ClusterFlow %s." % clusterflow_cli.VERSION in page


def test_help_is_readable():
    """--help is what a researcher sees first: description, plain placeholders, examples."""
    out = run("--help").stdout
    assert "Shows how much of their Slurm requests your jobs actually used" in out
    for flag in ("--days N", "--top N", "--csv PATH", "--html PATH", "--cpu-hour-cost RATE", "--gpu-hour-cost RATE",
                 "--currency SYMBOL"):
        assert flag in out, flag
    assert "json.dumps" not in out
    assert "print the full analysis as JSON instead of the text report" in " ".join(out.split())
    assert "Examples:" in out
    assert "clusterflow.py --demo" in out


def test_gpu_numbers_have_thousands_separators():
    """Found on the real IN2P3 month: 'GPU jobs: 1837', 'GPU-hours: 32154.6' among separated numbers."""
    summary = {"job_count": 5000, "avg_cpu_efficiency": 50, "avg_memory_efficiency": 50, "total_wasted_core_hours": 1,
               "gpu_job_count": 1837, "total_gpu_hours": 32154.6, "avg_gpu_utilization": None}
    text = clusterflow_cli.report({"summary": summary, "jobs": []}, 5)
    assert "GPU jobs:              1,837" in text
    assert "GPU-hours:             32,154.6" in text


def test_version_matches_handoff():
    """v0.28: VERSION stayed at 0.19 for nine releases, so reports named the wrong build. It must match the
    'Version' line in docs/HANDOFF.md, so a release that forgets to bump one of them fails here."""
    import re
    with open(os.path.join(ROOT, "docs", "HANDOFF.md"), encoding="utf-8") as f:
        m = re.search(r"^\| Version \| v([0-9.]+),", f.read(), re.M)
    assert m and m.group(1) == clusterflow_cli.VERSION
