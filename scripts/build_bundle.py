#!/usr/bin/env python3
"""
Build dist/clusterflow.py, the single-file ClusterFlow command-line tool.

Usage: python scripts/build_bundle.py [OUTPUT]

This script combines backend/analysis.py and backend/clusterflow_cli.py
into a single standalone file for cluster users.
"""

import os
import sys

# Get the project root directory (parent of scripts folder)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Read the analysis.py content
with open(os.path.join(ROOT, "backend", "analysis.py"), "r", encoding="utf-8") as f:
    analysis_source = f.read()

# Read the clusterflow_cli.py content
with open(os.path.join(ROOT, "backend", "clusterflow_cli.py"), "r", encoding="utf-8") as f:
    cli_source = f.read()

# Remove the two specific lines from CLI source
lines = cli_source.split('\n')
filtered_lines = []
for line in lines:
    # Skip these exact lines
    if line.strip() == 'sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))':
        continue
    elif line.strip().startswith('from analysis import '):
        continue
    else:
        filtered_lines.append(line)
cli_source_filtered = '\n'.join(filtered_lines)

# Create the output text
output_text = "#!/usr/bin/env python3\n"
output_text += "# ClusterFlow single-file build. Generated by scripts/build_bundle.py - do not edit.\n"
output_text += "# Source: backend/analysis.py + backend/clusterflow_cli.py\n\n"
output_text += analysis_source + "\n\n"
output_text += cli_source_filtered

# Determine output path
if len(sys.argv) > 1:
    output_path = sys.argv[1]
else:
    output_path = os.path.join(ROOT, "dist", "clusterflow.py")

# Create output directory if needed
os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)

# Write the file
with open(output_path, "w", encoding="utf-8", newline="\n") as f:
    f.write(output_text)

print(f"Wrote {output_path}")